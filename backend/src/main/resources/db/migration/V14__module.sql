-- US-18 Modules à venir dans un dossier. RG3 : la liste des modules est réglée ici, côté
-- serveur ; ajouter un module = une nouvelle migration qui insère une ligne, sans changer l'écran.
create table module (
    id          bigint generated by default as identity primary key,
    code        varchar(50)  not null unique,
    nom         varchar(100) not null,
    description varchar(255),
    statut      varchar(30)  not null default 'BIENTOT_DISPONIBLE' check (statut in ('BIENTOT_DISPONIBLE')),
    ordre       integer      not null
);

-- RG1 : tuiles CRM et Suivi des temps, « Bientôt disponible ».
insert into module (code, nom, description, ordre) values
    ('CRM', 'CRM', 'Suivez la relation avec le client du dossier.', 1),
    ('SUIVI_TEMPS', 'Suivi des temps', 'Saisissez le temps passé sur le dossier.', 2);
