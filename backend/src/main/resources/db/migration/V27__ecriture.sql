-- US-56 Générer les écritures d'une facture fournisseur validée (PTO-97).

-- RG1 : une écriture par facture d'achat validée, au journal des achats (AC). RG3 : datée de
-- l'émission de la facture, libellé « <tiers> <numéro> ». RG5 : re-générée (lignes remplacées) tant
-- qu'elle n'est pas exportée ; exportee_le reste vide jusqu'à l'export (EP-10). Supprimée avec sa
-- facture (US-16).
create table ecriture (
    id             bigint generated by default as identity primary key,
    dossier_id     bigint                   not null references dossier (id),
    facture_id     bigint                   not null unique references facture (id) on delete cascade,
    journal        varchar(10)              not null check (journal in ('AC')),
    date_ecriture  date                     not null,
    libelle        varchar(400)             not null,
    generee_le     timestamp with time zone not null,
    generee_par_id bigint                   not null references compte (id),
    exportee_le    timestamp with time zone
);

create index ecriture_dossier on ecriture (dossier_id);

-- RG1, RG4 : lignes de l'écriture (contrepartie au débit, une ligne de TVA par taux, 401 au crédit).
-- Le compte est un numéro du plan comptable du dossier (US-41) ; une ligne est au débit ou au crédit.
-- RG2 : total au débit = total au crédit, contrôlé à la génération et par la requête de l'US-30.
create table ligne_ecriture (
    id            bigint generated by default as identity primary key,
    ecriture_id   bigint         not null references ecriture (id) on delete cascade,
    ordre         integer        not null,
    numero_compte varchar(20)    not null,
    libelle       varchar(420)   not null,
    debit         numeric(12, 2) not null check (debit >= 0),
    credit        numeric(12, 2) not null check (credit >= 0),
    check (debit = 0 or credit = 0)
);

create index ligne_ecriture_ecriture on ligne_ecriture (ecriture_id);
create index ligne_ecriture_compte on ligne_ecriture (numero_compte);
