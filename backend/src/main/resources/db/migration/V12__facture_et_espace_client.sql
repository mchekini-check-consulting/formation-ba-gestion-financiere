-- US-09 Consulter la liste des dossiers du cabinet (nombre de factures, état de l'espace client),
-- préparé pour US-12/US-13 (factures) et US-14/US-08 (invitation du dirigeant).

-- Facture déposée dans un dossier : achat (facture fournisseur) ou vente (facture client).
-- Le fichier lui-même sera rangé avec l'US-13. ouverte_le vide = badge « Nouvelle » (US-12 RG3).
create table facture (
    id             bigint generated by default as identity primary key,
    dossier_id     bigint                   not null references dossier (id),
    sens           varchar(10)              not null check (sens in ('ACHAT', 'VENTE')),
    nom_fichier    varchar(255)             not null,
    type_fichier   varchar(100)             not null,
    deposee_le     timestamp with time zone not null,
    deposee_par_id bigint                   not null references compte (id),
    statut         varchar(20)              not null default 'RECUE' check (statut in ('RECUE')),
    ouverte_le     timestamp with time zone
);

create index facture_dossier on facture (dossier_id);

-- Espace client : le compte du dirigeant est rattaché à son dossier. État calculé :
-- aucun compte -> Non invité ; compte inactif -> Invité ; compte actif -> Actif.
alter table compte
    add column dossier_id bigint references dossier (id);

create index compte_dossier on compte (dossier_id);

-- US-14 RG2 : « Renvoyer l'invitation » annule le lien précédent.
alter table invitation
    add column annulee_le timestamp with time zone;
