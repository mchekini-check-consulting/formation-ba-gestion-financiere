-- US-53 Lire automatiquement une facture fournisseur.
-- RG6 : statut de la lecture ; vide pour les factures jamais lues (déposées avant l'US-53, factures clients).
alter table facture
    add column lecture_statut      varchar(20) check (lecture_statut in ('EN_COURS', 'LUE', 'ECHOUEE')),
    add column lecture_terminee_le timestamp with time zone,
    -- Au moins un champ « À vérifier » ou « À renseigner » : pastille « À vérifier » dans la liste.
    add column lecture_a_verifier  boolean;

-- RG2 : champs lus sur la facture (vides tant que la lecture n'est pas terminée ou si un champ n'est pas lu).
alter table facture
    add column type_tiers          varchar(20) check (type_tiers in ('FOURNISSEUR', 'CLIENT')),
    add column nom_tiers           varchar(255),
    add column numero_facture      varchar(100),
    add column date_emission       date,
    add column montant_ht          numeric(12, 2),
    add column montant_tva         numeric(12, 2),
    add column taux_tva            numeric(5, 2),
    add column montant_ttc         numeric(12, 2),
    add column compte_contrepartie varchar(20);

-- RG4 : niveau de confiance de chaque champ lu (0 à 1) ; a_verifier : doute (confiance basse ou
-- montants incohérents, RG5). Supprimé avec sa facture (US-16).
create table facture_champ_lu (
    id         bigint generated by default as identity primary key,
    facture_id bigint       not null references facture (id) on delete cascade,
    champ      varchar(30)  not null,
    confiance  numeric(4, 3) not null check (confiance between 0 and 1),
    a_verifier boolean      not null,
    unique (facture_id, champ)
);
