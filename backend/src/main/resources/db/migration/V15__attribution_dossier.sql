-- US-20 Attribuer les dossiers et limiter le comptable à ses dossiers (GF-32).

-- Comptable qui suit un dossier ; un dossier peut être suivi par plusieurs comptables.
-- RG1 : attribué par l'administrateur ou un associé (qui voient tous les dossiers).
-- RG2 : un comptable ne voit que les dossiers qui lui sont attribués.
create table dossier_attribution (
    id           bigint generated by default as identity primary key,
    dossier_id   bigint                   not null references dossier (id),
    comptable_id bigint                   not null references compte (id),
    attribue_le  timestamp with time zone not null,
    constraint dossier_attribution_unique unique (dossier_id, comptable_id)
);

create index dossier_attribution_comptable on dossier_attribution (comptable_id);

-- RG3 : un dossier créé par un comptable lui est attribué ; vaut aussi pour les dossiers existants.
insert into dossier_attribution (dossier_id, comptable_id, attribue_le)
select d.id, d.cree_par_id, d.cree_le
from dossier d
         join compte c on c.id = d.cree_par_id
where c.role_cabinet = 'COMPTABLE';
