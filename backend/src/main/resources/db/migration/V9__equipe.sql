-- US-19 Inviter un collaborateur avec un rôle (PTO-26).

-- RG2 : rôle du collaborateur dans son cabinet. Remplace la colonne « administrateur » (V8) :
-- l'administrateur qui a créé le cabinet (US-36) garde le rôle ADMINISTRATEUR.
-- Vide pour les comptes sans cabinet (dirigeants clients, comptes de démonstration).
alter table compte
    add column role_cabinet varchar(20) check (role_cabinet in ('ADMINISTRATEUR', 'ASSOCIE', 'COMPTABLE'));

update compte set role_cabinet = 'ADMINISTRATEUR' where administrateur;

alter table compte drop column administrateur;

-- Invitation d'un collaborateur : son compte existe déjà, inactif (« Invitée »), et sera
-- activé depuis le lien reçu par email (US-08 : valable 7 jours, une seule fois).
-- Seule l'empreinte du jeton du lien est stockée.
create table invitation (
    id              bigint generated by default as identity primary key,
    compte_id       bigint                   not null references compte (id),
    invitee_par_id  bigint                   not null references compte (id),
    empreinte_jeton varchar(64)              not null unique,
    envoyee_le      timestamp with time zone not null,
    expire_le       timestamp with time zone not null,
    utilisee_le     timestamp with time zone
);
