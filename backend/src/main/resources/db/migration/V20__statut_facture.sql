-- US-51 Suivre le statut de traitement d'une facture.
-- RG1 : quatre statuts ; les factures existantes restent « Reçue ».
alter table facture drop constraint facture_statut_check;
alter table facture
    add constraint facture_statut_check check (statut in ('RECUE', 'EN_COURS', 'TRAITEE', 'A_COMPLETER'));

-- RG3 : motif du statut « À compléter », affiché au client dans son espace ; vide pour les autres statuts.
alter table facture add column motif_a_completer varchar(255);

-- RG4 : chaque changement de statut garde son auteur et sa date. Supprimé avec sa facture (US-16).
create table facture_statut_historique (
    id             bigint generated by default as identity primary key,
    facture_id     bigint                   not null references facture (id) on delete cascade,
    ancien_statut  varchar(20)              not null,
    nouveau_statut varchar(20)              not null,
    motif          varchar(255),
    modifie_par_id bigint                   not null references compte (id),
    modifie_le     timestamp with time zone not null
);

create index facture_statut_historique_facture on facture_statut_historique (facture_id);
