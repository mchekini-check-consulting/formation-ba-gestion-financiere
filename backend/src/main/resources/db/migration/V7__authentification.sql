-- Authentification (EP-02) : code SMS (US-04), blocage après 3 échecs (US-05),
-- réinitialisation du mot de passe (US-06), sessions et expiration (US-07).
-- Aucun secret en clair : codes, liens et sessions ne sont stockés que sous forme d'empreinte.

alter table compte
    add column nom_affiche        varchar(200) not null default '',
    add column telephone          varchar(20)  not null default '',
    add column echecs_consecutifs integer      not null default 0,
    add column bloque_jusqu_a     timestamp with time zone;

-- Comptes de démonstration (V6) : nom affiché et numéro fictif pour le code SMS.
update compte set nom_affiche = 'Jean Dupont', telephone = '0612345642'
    where email = 'jean.dupont@cabinet-test.fr';
update compte set nom_affiche = 'Sophie Martin', telephone = '0698765413'
    where email = 'sophie.martin@boulangerie-test.fr';

-- US-04 : un code SMS par tentative de connexion ("défi"), valable 5 minutes.
create table code_sms (
    id             bigint generated by default as identity primary key,
    compte_id      bigint                   not null references compte (id),
    empreinte_defi varchar(64)              not null unique,
    empreinte_code varchar(100)             not null,
    envoye_le      timestamp with time zone not null,
    expire_le      timestamp with time zone not null,
    codes_faux     integer                  not null default 0,
    termine        boolean                  not null default false
);

-- US-06 : lien de réinitialisation, valable 1 heure, utilisable une seule fois.
create table jeton_reinitialisation (
    id              bigint generated by default as identity primary key,
    compte_id       bigint                   not null references compte (id),
    empreinte_jeton varchar(64)              not null unique,
    expire_le       timestamp with time zone not null,
    utilise_le      timestamp with time zone
);

-- US-07 : sessions ouvertes après le code SMS ; expirent après 30 minutes sans activité.
create table session_utilisateur (
    id                bigint generated by default as identity primary key,
    compte_id         bigint                   not null references compte (id),
    empreinte_jeton   varchar(64)              not null unique,
    derniere_activite timestamp with time zone not null,
    fermee            boolean                  not null default false
);
