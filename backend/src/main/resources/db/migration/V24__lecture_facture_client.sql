-- US-54 Lire automatiquement une facture client (et CA2 : plusieurs taux de TVA, aussi pour les
-- factures fournisseurs de l'US-53, lues par le même service).

-- CA2 : vrai si la facture porte plusieurs taux de TVA (taux_tva reste vide, la fiche affiche
-- « Multiple ») ; vide pour une facture jamais lue.
alter table facture
    add column taux_tva_multiple boolean;

-- CA2 : détail de la TVA lue, une ligne par taux, conservé pour la fiche. base_ht vide si la
-- facture ne donne que le montant de TVA du taux. Supprimé avec sa facture (US-16).
create table facture_tva_lue (
    id          bigint generated by default as identity primary key,
    facture_id  bigint        not null references facture (id) on delete cascade,
    taux        numeric(5, 2) not null,
    base_ht     numeric(12, 2),
    montant_tva numeric(12, 2) not null,
    unique (facture_id, taux)
);
