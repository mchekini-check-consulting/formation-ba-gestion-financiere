-- US-41 Paramétrer le plan comptable du dossier (PTO-66).

-- RG1 : plan comptable général (simplifié : comptes courants des classes 1 à 7), modèle copié
-- dans chaque dossier à sa création. Ajouter un compte au modèle = une nouvelle migration (les
