-- Plan comptable d'un dossier : comptes du plan général (sous_compte = false) et sous-comptes
-- ajoutés par la comptable (RG1, ex. 401MOULINS). RG3 : un compte se désactive (actif = false)
-- au lieu d'être supprimé s'il est déjà utilisé dans une écriture (US-30).
create table compte_comptable (
    id          bigint generated by default as identity primary key,
    dossier_id  bigint                   not null references dossier (id),
    numero      varchar(20)              not null check (numero ~ '^[1-7][0-9]{2}[0-9A-Z]{0,17}$'),
    libelle     varchar(200)             not null,
    sous_compte boolean                  not null,
    actif       boolean                  not null default true,
    cree_le     timestamp with time zone not null,
    constraint compte_comptable_numero_unique_par_dossier unique (dossier_id, numero)
);

-- RG1 : les dossiers déjà créés démarrent eux aussi avec le plan général.
insert into compte_comptable (dossier_id, numero, libelle, sous_compte, actif, cree_le)
select d.id, p.numero, p.libelle, false, true, now()
from dossier d cross join plan_comptable_general p;

-- RG2 : catégories de transaction ou de facture, chacune avec son compte par défaut.
create table categorie (
    id             bigint generated by default as identity primary key,
    code           varchar(50)  not null unique,
    libelle        varchar(100) not null,
    numero_compte  varchar(20)  not null references plan_comptable_general (numero),
    ordre          integer      not null
);

