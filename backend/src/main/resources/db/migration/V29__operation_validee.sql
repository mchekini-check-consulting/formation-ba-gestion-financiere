-- US-30 Générer les écritures comptables des opérations bancaires validées (PTO-55).

-- RG1 : une opération bancaire validée (onglet Banque) avec sa catégorie (US-41 RG2 : Achat, Vente,
-- Frais bancaires), son compte (par défaut celui de la catégorie) et son taux de TVA. L'opération elle-même vient du bouchon ou de la banque (US-58) : on garde ici ce qu'elle était
-- au moment de la validation. reference : identifiant stable de l'opération chez son fournisseur.
create table operation_validee (
    id             bigint generated by default as identity primary key,
    dossier_id     bigint                   not null references dossier (id),
    reference      varchar(100)             not null,
    date_operation date                     not null,
    libelle        varchar(300)             not null,
    tiers          varchar(255),
    montant        numeric(12, 2)           not null check (montant > 0),
    sens           varchar(10)              not null check (sens in ('ENTREE', 'SORTIE')),
    source         varchar(10)              not null check (source in ('BOUCHON', 'BANQUE')),
    categorie      varchar(50)              not null references categorie (code),
    numero_compte  varchar(20)              not null,
    taux_tva       numeric(5, 2)            not null check (taux_tva >= 0 and taux_tva <= 100),
    validee_le     timestamp with time zone not null,
    validee_par_id bigint                   not null references compte (id),
    unique (dossier_id, reference)
);

-- RG1 : une écriture vient d'une facture (US-56, US-57) ou d'une opération bancaire (journal de
-- banque BQ), jamais des deux. Ajouts seulement : l'ancienne version du code continue d'écrire des
-- écritures de facture pendant le déploiement.
alter table ecriture alter column facture_id drop not null;
alter table ecriture add column operation_id bigint unique references operation_validee (id) on delete cascade;
alter table ecriture add constraint ecriture_origine check ((facture_id is null) <> (operation_id is null));
alter table ecriture drop constraint ecriture_journal_check;
alter table ecriture add constraint ecriture_journal_check check (journal in ('AC', 'VT', 'BQ'));
