-- Comptes utilisateurs (US-03 Se connecter) : collaborateurs de cabinet et dirigeants clients.
-- L'email est l'identifiant ; il est stocké en minuscules (RG1) et unique sans tenir compte
-- des majuscules. Le mot de passe n'est jamais stocké en clair : empreinte BCrypt uniquement.
create table compte (
    id                bigint generated by default as identity primary key,
    email             varchar(254) not null,
    mot_de_passe_hash varchar(100) not null,
    role              varchar(20)  not null check (role in ('COLLABORATEUR', 'DIRIGEANT')),
    actif             boolean      not null default true
);

create unique index compte_email_unique on compte (lower(email));
