-- US-36 Connaître le tarif et créer le compte de son cabinet (PTO-61).

-- Cabinet d'expertise comptable. RG2 : un SIREN ne peut servir qu'à un seul cabinet.
create table cabinet (
    id                     bigint generated by default as identity primary key,
    nom                    varchar(200)             not null,
    siren                  varchar(9)               not null unique,
    nombre_dossiers_prevus integer                  not null check (nombre_dossiers_prevus > 0),
    -- Code saisi à l'inscription ; il ne donne droit à rien avant la US-44 (parrainage).
    code_parrainage_saisi  varchar(20),
    cgu_acceptees_le       timestamp with time zone not null,
    cree_le                timestamp with time zone not null
);

-- RG3 : la personne qui crée le compte du cabinet en devient administratrice.
-- Les comptes de démonstration (V6) ne sont rattachés à aucun cabinet.
alter table compte
    add column cabinet_id     bigint references cabinet (id),
    add column administrateur boolean not null default false;

-- RG3 : inscription en cours, entre le formulaire et le code SMS qui confirme le mobile.
-- Le cabinet et le compte ne sont créés qu'après le bon code : une inscription abandonnée
-- ne bloque ni le SIREN ni l'email. Mot de passe, défi et code : empreintes uniquement.
create table inscription (
    id                     bigint generated by default as identity primary key,
    nom_cabinet            varchar(200)             not null,
    siren                  varchar(9)               not null,
    prenom                 varchar(100)             not null,
    nom                    varchar(100)             not null,
    email                  varchar(254)             not null,
    telephone              varchar(20)              not null,
    mot_de_passe_hash      varchar(100)             not null,
    nombre_dossiers_prevus integer                  not null,
    code_parrainage_saisi  varchar(20),
    cgu_acceptees_le       timestamp with time zone not null,
    empreinte_defi         varchar(64)              not null unique,
    empreinte_code         varchar(100)             not null,
    envoye_le              timestamp with time zone not null,
    expire_le              timestamp with time zone not null,
    codes_faux             integer                  not null default 0,
    terminee               boolean                  not null default false
);
