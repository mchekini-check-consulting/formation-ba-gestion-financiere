-- US-55 Vérifier, corriger et valider les informations d'une facture.
-- RG8 : chaque modification d'un champ de la fiche garde l'ancienne et la nouvelle valeur, son
-- auteur et sa date. Supprimée avec sa facture (US-16).
create table facture_modification (
    id              bigint generated by default as identity primary key,
    facture_id      bigint                   not null references facture (id) on delete cascade,
    champ           varchar(30)              not null,
    ancienne_valeur varchar(255),
    nouvelle_valeur varchar(255),
    modifie_par_id  bigint                   not null references compte (id),
    modifie_le      timestamp with time zone not null
);

create index facture_modification_facture on facture_modification (facture_id);
