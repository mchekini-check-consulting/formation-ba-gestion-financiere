-- US-55 Vérifier, corriger et valider les informations d'une facture.
-- RG8 : chaque modification des informations d'une facture garde son auteur et sa date, avec la
-- liste des champs modifiés (noms des champs, jamais leurs valeurs). Supprimé avec sa facture (US-16).
create table facture_correction (
    id             bigint generated by default as identity primary key,
    facture_id     bigint                   not null references facture (id) on delete cascade,
    champs         varchar(300)             not null,
    modifie_par_id bigint                   not null references compte (id),
    modifie_le     timestamp with time zone not null
);

create index facture_correction_facture on facture_correction (facture_id);
