-- US-10 Créer un dossier client (PTO-17).

-- Dossier d'un client du cabinet, qui y recevra ses factures.
-- RG1 : raison sociale et SIREN (9 chiffres) obligatoires.
-- RG2 : un SIREN ne peut exister qu'une fois dans un même cabinet ; deux cabinets différents
-- peuvent suivre la même entreprise.
create table dossier (
    id             bigint generated by default as identity primary key,
    cabinet_id     bigint                   not null references cabinet (id),
    raison_sociale varchar(200)             not null,
    siren          varchar(9)               not null check (siren ~ '^[0-9]{9}$'),
    cree_par_id    bigint                   not null references compte (id),
    cree_le        timestamp with time zone not null,
    constraint dossier_siren_unique_par_cabinet unique (cabinet_id, siren)
);
